-- ============================================================================
-- Bhubharati Simple H2 Database Schema
--
-- Hierarchy:
-- District -> Mandal -> Village -> Survey Number -> Khata Number
--
-- Database:
-- ./data/bhubharati.mv.db
--
-- NOTE:
-- Keep the database simple.
-- No indexes, foreign keys, views or unique constraints.
-- ============================================================================


-- ============================================================================
-- DISTRICT
--
-- id                  = Bhubharati District ID
-- state               = State name
-- district_name       = District name in English
-- telugu_name         = District name in Telugu
-- source              = Data source
-- source_last_updated = Source data updated date
--
-- Example:
-- id = 10 -> Siddipet
-- ============================================================================

CREATE TABLE IF NOT EXISTS district (
    id INTEGER PRIMARY KEY,
    state VARCHAR(100),
    district_name VARCHAR(150),
    telugu_name VARCHAR(200),
    source VARCHAR(100),
    source_last_updated DATE
);


-- ============================================================================
-- MANDAL
--
-- id                  = Internal database sequence ID
-- district_id         = Bhubharati District ID
-- mandal_id           = Bhubharati Mandal ID
-- mandal_name         = Mandal name in English
-- telugu_name         = Mandal name in Telugu
-- source_last_updated = Source data updated date
-- ============================================================================

CREATE TABLE IF NOT EXISTS mandal (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id INTEGER,
    mandal_id INTEGER,
    mandal_name VARCHAR(150),
    telugu_name VARCHAR(200),
    source_last_updated DATE
);


-- ============================================================================
-- VILLAGE
--
-- id                  = Internal database sequence ID
-- district_id         = Bhubharati District ID
-- mandal_id           = Bhubharati Mandal ID
-- village_id          = Bhubharati Village ID
-- village_name        = Village name in English
-- telugu_name         = Village name in Telugu
-- source_last_updated = Source data updated date
-- ============================================================================

CREATE TABLE IF NOT EXISTS village (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id INTEGER,
    mandal_id INTEGER,
    village_id BIGINT,
    village_name VARCHAR(150),
    telugu_name VARCHAR(200),
    source_last_updated DATE
);


-- ============================================================================
-- SURVEY NUMBER
--
-- id           = Internal sequence ID
-- district_id  = Bhubharati District ID
-- mandal_id    = Bhubharati Mandal ID
-- village_id   = Bhubharati Village ID
-- survey_no    = Survey Number
-- khata_no     = Khata Number
-- source_error = Error returned while retrieving survey/khata data
--
-- survey_no and khata_no are VARCHAR because values may contain:
--   - Telugu characters
--   - Slash (/)
--   - English characters
--   - Leading zeros
--   - Sub-division values
--
-- One survey can have multiple Khata numbers.
-- In that case each Survey + Khata combination is a separate row.
--
-- Example:
--
-- district_id = 10
-- mandal_id   = 205
-- village_id  = 1019004
-- survey_no   = 1147
-- khata_no    = 61181
-- ============================================================================

CREATE TABLE IF NOT EXISTS survey_number (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    district_id INTEGER,
    mandal_id INTEGER,
    village_id BIGINT,
    survey_no VARCHAR(150),
    khata_no VARCHAR(100),
    source_error VARCHAR(1000)
);